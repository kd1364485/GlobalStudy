"""LLM プロンプトの組立て。

プロンプト改善（Phase 7）はこのモジュールのみを変更する。
"""

_ANALYSIS_PROMPT_TEMPLATE = """\
あなたはあらゆる分野に精通した優秀な教育者です。
英語の動画を視聴している日本人学習者を支援します。

以下はスクリーンキャプチャからOCRで抽出した英文です。
まず本文の分野（例: AI、プログラミング、哲学、生物学、歴史、経済など）を自分で判断し、
その分野の専門家・教育者として回答してください。

注意事項:
- OCR由来の誤字・脱字・行の分断は文脈から補正して解釈すること
- 直訳ではなく、その分野で通用する自然な日本語にすること
- 分野特有の定訳・慣用表現がある場合はそれを使うこと（例: attention → アテンション、
  categorical imperative → 定言命法、natural selection → 自然選択）
- 推測で内容を追加しないこと。本文にある情報のみを扱うこと

英文:
{text}

必ず次の6セクションの形式で日本語で出力してください。見出し（【】）は変更しないでください。

【日本語訳】
文脈を踏まえた自然な日本語訳

【重要ポイント】
本文の要点を「- 」の箇条書きで2〜4個

【専門用語】
その分野の学習者が知っておくべき用語を「- 用語（原語）: 解説」の箇条書きで簡潔に（なければ「なし」）

【初心者向け説明】
この分野を初めて学ぶ人にも伝わるよう、身近な例えを交えて2〜3文で説明

【背景知識】
この内容を理解するために役立つ前提知識を2〜3文で解説（本文に書かれていない周辺知識を補足）

【関連概念】
この内容に関連する概念やトピックを「- 概念名: 簡潔な説明」の箇条書きで2〜4個（なければ「なし」）
"""


def build_analysis_prompt(english_text: str) -> str:
    """OCR で抽出した英文から解析用プロンプトを組み立てる。"""
    return _ANALYSIS_PROMPT_TEMPLATE.format(text=english_text)
